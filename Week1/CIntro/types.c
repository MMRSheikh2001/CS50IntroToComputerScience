#include <stdio.h>

int main()
{

    int a = 10;
    float b = 10.5;
    double c = 104556.4545;

    bool d = false;

    char e = 'A';

    long f = 632753268;

    printf("Integer : %i\n", a);
    printf("Float : %f \n", b);
    printf("Double : %f \n", c);
    printf("Boolean :  %d \n", d);
    printf("Character : %c \n", e);
    printf("Long : %li \n", f);

    return 0;
}